-- =====================================================================
-- AgroRetorno - V1: esquema inicial (PostgreSQL)
-- Tablas principales del sistema de préstamos de materiales agrícolas.
-- =====================================================================

-- Usuarios del sistema (credenciales protegidas con BCrypt)
CREATE TABLE usuarios (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username        VARCHAR(50)  NOT NULL UNIQUE,
    password_hash   VARCHAR(100) NOT NULL,
    nombre_completo VARCHAR(150) NOT NULL,
    rol             VARCHAR(20)  NOT NULL CHECK (rol IN ('PRODUCTOR', 'ENCARGADO')),
    activo          BOOLEAN      NOT NULL DEFAULT TRUE,
    fecha_registro  TIMESTAMP    NOT NULL
);

-- Productores agrícolas asociados a una cuenta de usuario
CREATE TABLE productores (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id          BIGINT       NOT NULL UNIQUE REFERENCES usuarios (id),
    dni                 VARCHAR(8)   NOT NULL UNIQUE CHECK (dni ~ '^[0-9]{8}$'),
    nombres             VARCHAR(80)  NOT NULL,
    apellidos           VARCHAR(80)  NOT NULL,
    telefono            VARCHAR(9),
    sector              VARCHAR(100) NOT NULL,
    fecha_registro      TIMESTAMP    NOT NULL,
    fecha_actualizacion TIMESTAMP
);

-- Materiales reutilizables
CREATE TABLE materiales (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo         VARCHAR(20)  NOT NULL UNIQUE,
    nombre         VARCHAR(100) NOT NULL,
    categoria      VARCHAR(30)  NOT NULL CHECK (categoria IN
                       ('JABAS_COSECHA', 'CARRETILLAS', 'BALANZAS', 'FUMIGADORAS', 'HERRAMIENTAS')),
    descripcion    VARCHAR(500),
    unidad         VARCHAR(30)  NOT NULL,
    estado         VARCHAR(10)  NOT NULL CHECK (estado IN ('ACTIVO', 'INACTIVO')),
    fecha_registro TIMESTAMP    NOT NULL
);

-- Existencias por material.
-- Regla de integridad: total = disponible + prestada + dañada + mantenimiento
CREATE TABLE inventario (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    material_id            BIGINT    NOT NULL UNIQUE REFERENCES materiales (id),
    cantidad_total         INTEGER   NOT NULL CHECK (cantidad_total >= 0),
    cantidad_disponible    INTEGER   NOT NULL CHECK (cantidad_disponible >= 0),
    cantidad_prestada      INTEGER   NOT NULL CHECK (cantidad_prestada >= 0),
    cantidad_danada        INTEGER   NOT NULL CHECK (cantidad_danada >= 0),
    cantidad_mantenimiento INTEGER   NOT NULL CHECK (cantidad_mantenimiento >= 0),
    fecha_actualizacion    TIMESTAMP NOT NULL,
    CONSTRAINT ck_inventario_cuadre CHECK (
        cantidad_total = cantidad_disponible + cantidad_prestada + cantidad_danada + cantidad_mantenimiento)
);

-- Solicitudes de préstamo
CREATE TABLE solicitudes (
    id                        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    productor_id              BIGINT       NOT NULL REFERENCES productores (id),
    material_id               BIGINT       NOT NULL REFERENCES materiales (id),
    cantidad                  INTEGER      NOT NULL CHECK (cantidad > 0),
    fecha_solicitud           TIMESTAMP    NOT NULL,
    fecha_devolucion_prevista DATE         NOT NULL,
    motivo                    VARCHAR(300) NOT NULL,
    estado                    VARCHAR(15)  NOT NULL CHECK (estado IN ('PENDIENTE', 'APROBADA', 'RECHAZADA', 'ENTREGADA')),
    respondido_por            BIGINT REFERENCES usuarios (id),
    fecha_respuesta           TIMESTAMP,
    motivo_rechazo            VARCHAR(300)
);

-- Préstamos (entregas físicas). UNIQUE(solicitud_id): una solicitud genera como máximo un préstamo.
CREATE TABLE prestamos (
    id                        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    solicitud_id              BIGINT      NOT NULL UNIQUE REFERENCES solicitudes (id),
    cantidad_entregada        INTEGER     NOT NULL CHECK (cantidad_entregada > 0),
    cantidad_devuelta         INTEGER     NOT NULL DEFAULT 0 CHECK (cantidad_devuelta >= 0),
    cantidad_buen_estado      INTEGER     NOT NULL DEFAULT 0 CHECK (cantidad_buen_estado >= 0),
    cantidad_danada           INTEGER     NOT NULL DEFAULT 0 CHECK (cantidad_danada >= 0),
    cantidad_mantenimiento    INTEGER     NOT NULL DEFAULT 0 CHECK (cantidad_mantenimiento >= 0),
    fecha_entrega             TIMESTAMP   NOT NULL,
    fecha_devolucion_prevista DATE        NOT NULL,
    estado                    VARCHAR(10) NOT NULL CHECK (estado IN ('ACTIVO', 'CERRADO')),
    entregado_por             BIGINT      NOT NULL REFERENCES usuarios (id),
    fecha_cierre              TIMESTAMP,
    CONSTRAINT ck_prestamo_devuelto CHECK (cantidad_devuelta <= cantidad_entregada),
    CONSTRAINT ck_prestamo_clasificado CHECK (
        cantidad_devuelta = cantidad_buen_estado + cantidad_danada + cantidad_mantenimiento)
);

-- Cada operación de devolución (puede haber varias por préstamo: devoluciones parciales)
CREATE TABLE devoluciones (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    prestamo_id   BIGINT       NOT NULL REFERENCES prestamos (id),
    fecha         TIMESTAMP    NOT NULL,
    recibido_por  BIGINT       NOT NULL REFERENCES usuarios (id),
    observaciones VARCHAR(500)
);

-- Detalle por condición de las unidades recibidas en una devolución
CREATE TABLE detalles_devolucion (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    devolucion_id   BIGINT      NOT NULL REFERENCES devoluciones (id),
    estado_material VARCHAR(25) NOT NULL CHECK (estado_material IN ('BUEN_ESTADO', 'DANADO', 'REQUIERE_MANTENIMIENTO')),
    cantidad        INTEGER     NOT NULL CHECK (cantidad > 0),
    CONSTRAINT uq_detalle_condicion UNIQUE (devolucion_id, estado_material)
);

-- Movimientos de existencias (altas, entregas, devoluciones, ajustes)
CREATE TABLE movimientos_inventario (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    material_id BIGINT       NOT NULL REFERENCES materiales (id),
    tipo        VARCHAR(30)  NOT NULL,
    cantidad    INTEGER      NOT NULL CHECK (cantidad > 0),
    fecha       TIMESTAMP    NOT NULL,
    usuario_id  BIGINT       NOT NULL REFERENCES usuarios (id),
    referencia  VARCHAR(100),
    observacion VARCHAR(300)
);

-- Historial de operaciones relevantes (trazabilidad / auditoría)
CREATE TABLE historial_operaciones (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha_hora TIMESTAMP     NOT NULL,
    actor      VARCHAR(50)   NOT NULL,
    accion     VARCHAR(50)   NOT NULL,
    entidad    VARCHAR(50)   NOT NULL,
    entidad_id BIGINT,
    detalle    VARCHAR(1000)
);
